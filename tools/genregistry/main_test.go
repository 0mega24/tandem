func TestRun(t *testing.T) {
	root := t.TempDir()
	write(t, root, "go.mod", "module example.com/m\n\ngo 1.27\n")
	gen := filepath.Join(root, "internal/gen")
	write(t, gen, "gen.go", "package gen\n")
	generator(t, gen, "zig")
	generator(t, gen, "golang")
	write(t, gen, "gentest/gentest.go", "package gentest\n") // support: not a generator
	write(t, gen, "all/zz_generated_imports.go", "package all\n")

	if err := run(gen, "all/zz_generated_imports.go"); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(filepath.Join(gen, "all/zz_generated_imports.go"))
	if err != nil {
		t.Fatal(err)
	}
	want := `// Code generated by genregistry. DO NOT EDIT.

// Package all imports every built-in generator, so that each one registers itself.
package all

import (
	_ "example.com/m/internal/gen/golang"
	_ "example.com/m/internal/gen/zig"
)
`
	if string(got) != want {
		t.Errorf("imports file:\n%s\nwant:\n%s", got, want)
	}
}

func TestRunRejectsIncompleteGenerators(t *testing.T) {
	root := t.TempDir()
	write(t, root, "go.mod", "module example.com/m\n")
	gen := filepath.Join(root, "internal/gen")
	generator(t, gen, "zig")
	write(t, gen, "zig/zig.go", "package zig\n\nfunc init() {}\n")
	if err := os.RemoveAll(filepath.Join(gen, "zig/testdata/mixed")); err != nil {
		t.Fatal(err)
	}
	write(t, gen, "bare/bare.go", "package bare\n")

	err := run(gen, "all/zz_generated_imports.go")
	if err == nil {
		t.Fatal("run = nil, want the problems")
	}
	for _, want := range []string{
		"zig: no golden case testdata/mixed", "zig: no init() that calls gen.Register",
		"bare: no doc.go", "bare: no golden case testdata/depends",
	} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("error %q, want it to contain %q", err, want)
		}
	}
	if _, err := os.Stat(filepath.Join(gen, "all")); !os.IsNotExist(err) {
		t.Error("wrote the imports file despite the problems")
	}
}
