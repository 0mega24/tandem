// Package gen is the generator API: each language package (internal/gen/<id>) finds its
// manifests in the worktrees of a space and plans the workspace files that connect them.
//
// Generators are pure. Detect only reads files in one worktree, and Plan does no I/O at all;
// only apply.go writes. So a generator is tested with golden files and cannot damage a space.
package gen

// Member is one feature-branch worktree in the space. Symlinked always.repos are never Members:
// they are the main clones, which a space must not change.
type Member struct {
	Name         string // short name, e.g. "myorg/api"
	WorktreePath string // absolute
	RepoPath     string // main clone, absolute
	OriginURL    string // "" when the repo has no origin
}

// Space is the input to Plan.
type Space struct {
	Name    string         // the space name, for the ownership header
	Root    string         // absolute
	Branch  string         // the branch of all worktrees
	Members []Member       // sorted by Name
	Config  map[string]any // the [generate.<id>] table; decode it with DecodeConfig
}

// DetectOptions are the settings that Detect may use.
type DetectOptions struct {
	Depth  int            // generate.detect_depth: directory levels below the root to look in too
	Config map[string]any // the [generate.<id>] table, the same one that Plan gets
}

// Detection is what one generator found in one Member.
type Detection struct {
	Member   Member         // the worktree that has the manifest
	Manifest string         // relative to the worktree, with "/", e.g. "go.mod"
	Facts    map[string]any // what Plan needs: module paths, versions, names
}

// File is one file that a Plan writes.
type File struct {
	Path    string // relative to the space root, with "/"
	Content []byte
}

// Link is a symlink that a Plan makes. Only meson needs one: subprojects/<dir> in a consumer
// worktree, the one exception to the rule that a plan writes nothing inside a member.
type Link struct {
	Path   string // relative to the space root, with "/"
	Target string // absolute path that the link points to
}

// Plan is what one generator writes for the members that it found.
type Plan struct {
	Files    []File   // sorted by Path
	Links    []Link   // sorted by Path
	Stale    []string // files that tools derive from Files, deleted when Files change, e.g. "go.work.sum"
	Warnings []string // shown to the user; never fatal
}

// Meta describes a generator for the registry, the docs and the config schema.
type Meta struct {
	ID        string   // config and CLI name, e.g. "go"
	Languages []string // for the docs
	Manifests []string // the files that Detect looks for, for the docs
	DefaultOn bool     // used when generate.enabled is not set
	Release   int      // the release that it came in
	Config    any      // the default [generate.<id>] values; nil when it has none
}

// Generator is one language or build system.
type Generator interface {
	Meta() Meta

	// Detect reads only files in m.WorktreePath and runs no subprocess. It returns nil, nil
	// when the member is not for this generator.
	Detect(m Member, o DetectOptions) (*Detection, error)

	// Plan is pure: no I/O, and the same bytes for the same input. With no detections it
	// returns an empty Plan, not an error.
	Plan(s Space, found []Detection) (Plan, error)
}

// Header is the ownership line at the top of each generated file that has comments. JSON has
// none; the hash in the state file is its only ownership record.
func Header(space string) string {
	return "Generated by tandem for space " + space + ". Do not edit. Run 'tdm generate " + space + "' to update."
}
